import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import { icons } from 'lucide';

await mkdir('public/assets', { recursive: true });
const selected = ['LayoutDashboard', 'FolderOpen', 'ArrowLeftRight', 'Database', 'Bell', 'Moon', 'Sun', 'ShieldCheck', 'PanelLeft', 'ChevronRight', 'ChevronDown', 'Clock3', 'Layers2', 'Download', 'Upload', 'Info', 'ArrowUpRight', 'CircleCheck', 'TriangleAlert', 'CircleAlert', 'Wallet', 'ChartNoAxesCombined', 'RefreshCw', 'ReceiptText', 'Search', 'ArrowDownLeft'];
const output = Object.fromEntries(selected.map(name => {
  if (!icons[name]) throw new Error(`Missing Lucide icon: ${name}`);
  return [name.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/([a-z])(\d)/g, '$1-$2').toLowerCase(), icons[name]];
}));
await writeFile('public/assets/icons.js', `// Selected Lucide icons. Generated by scripts/prepare-assets.mjs.\nexport const icons = ${JSON.stringify(output)};\n`);
await copyFile('node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2', 'public/assets/geist-latin.woff2');
await copyFile('node_modules/@fontsource-variable/geist/LICENSE', 'public/assets/GEIST-LICENSE.txt');
await copyFile('node_modules/lucide/LICENSE', 'public/assets/LUCIDE-LICENSE.txt');
console.log('Prepared local Geist font and selected Lucide icons.');
